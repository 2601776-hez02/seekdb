std::string temp_path(const char *name)
{
  std::string directory;
  const char *tmp = getenv("TEST_TMPDIR");
  if (nullptr == tmp) {
    tmp = getenv("TMPDIR");
  }
  directory = (nullptr == tmp) ? "/tmp" : tmp;
  return directory + "/" + name;
}

bool write_file(const std::string &path, const char *data, const int64_t length)
{
  bool ok = false;
  FILE *file = fopen(path.c_str(), "wb");
  if (nullptr != file) {
    ok = length == static_cast<int64_t>(fwrite(data, 1, static_cast<size_t>(length), file));
    fclose(file);
  }
  return ok;
}

struct ReadResult
{
  Status status_ = Status::OK;
  std::string error_;
  std::vector<Column> columns_;
  std::vector<std::vector<std::string>> rows_;
};

std::string cell_text(const Cell &cell, const ColumnType type)
{
  std::string text;
  if (cell.is_null_) {
    text = "NULL";
  } else if (ColumnType::BOOLEAN == type) {
    text = cell.bool_value_ ? "true" : "false";
  } else if (ColumnType::BIGINT == type) {
    text = std::to_string(cell.int_value_);
  } else if (ColumnType::DOUBLE == type) {
    text = format_double(cell.double_value_);
  } else {
    text = cell.text_;
  }
  return text;
}

ReadResult read_all(const std::string &path, const Options &options,
                    const std::vector<int64_t> &needed = std::vector<int64_t>())
{
  ReadResult result;
  result.status_ = infer_schema(path, options, result.columns_, result.error_);
  if (Status::OK != result.status_) {
    return result;
  }
  IRecordReader *reader = nullptr;
  result.status_ = create_reader(path, options, result.columns_, needed, reader, result.error_);
  if (Status::OK == result.status_) {
    result.status_ = reader->open(result.error_);
  }
  while (Status::OK == result.status_) {
    Row row;
    bool eof = false;
    result.status_ = reader->next(row, eof, result.error_);
    if (Status::OK != result.status_ || eof) {
      break;
    }
    std::vector<std::string> cells;
    for (size_t i = 0; i < result.columns_.size(); ++i) {
      cells.push_back(i < row.cells_.size() ? cell_text(row.cells_[i], result.columns_[i].type_)
                                            : "NULL");
    }
    result.rows_.push_back(cells);
  }
  if (nullptr != reader) {
    destroy_reader(reader);
  }
  return result;
}

std::string describe(const std::vector<Column> &columns)
{
  std::string text;
  for (size_t i = 0; i < columns.size(); ++i) {
    if (!text.empty()) {
      text += ",";
    }
    text += columns[i].name_;
    text += ":";
    text += column_type_name(columns[i].type_);
  }
  return text;
}

