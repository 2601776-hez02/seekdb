TEST(FileSqlScanUtils, jsonl_builds_the_field_union_and_rejects_nesting)
{
  const std::string path = temp_path("file_sql_jsonl.jsonl");
  const char *content =
      "{\"id\": 1, \"name\": \"alice\", \"score\": 1.5, \"active\": true}\n"
      "\n"
      "{\"id\": 2, \"extra\": \"x\"}\n"
      "{\"id\": 3, \"score\": 2, \"name\": \"\\u4f60\\u597d\"}\n"
      "{\"id\": 4, \"name\": 42, \"score\": null}\n";
  ASSERT_TRUE(write_file(path, content, static_cast<int64_t>(strlen(content))));
  Options options;
  options.format_ = FileFormat::JSON;
  const ReadResult result = read_all(path, options);
  EXPECT_EQ(Status::OK, result.status_) << result.error_;
  EXPECT_EQ("id:bigint,name:varchar,score:double,active:boolean,extra:varchar",
            describe(result.columns_));
  ASSERT_EQ(4, static_cast<int>(result.rows_.size()));
  EXPECT_EQ("2|NULL|NULL|NULL|x", result.rows_[1][0] + "|" + result.rows_[1][1] + "|" +
                                      result.rows_[1][2] + "|" + result.rows_[1][3] + "|" +
                                      result.rows_[1][4]);
  EXPECT_EQ("\xe4\xbd\xa0\xe5\xa5\xbd", result.rows_[2][1]);
  EXPECT_EQ("42", result.rows_[3][1]);
  EXPECT_EQ("NULL", result.rows_[3][2]);
  unlink(path.c_str());

  const std::string nested = temp_path("file_sql_jsonl_nested.jsonl");
  const char *nested_content = "{\"id\": 1, \"obj\": {\"a\": 1}}\n";
  ASSERT_TRUE(write_file(nested, nested_content, static_cast<int64_t>(strlen(nested_content))));
  const ReadResult rejected = read_all(nested, options);
  EXPECT_EQ(Status::PARSE_ERROR, rejected.status_);
  EXPECT_NE(std::string::npos, rejected.error_.find("nested"));
  unlink(nested.c_str());
}

