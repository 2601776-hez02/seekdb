TEST(FileSqlScanUtils, csv_infers_schema_and_decodes_quoted_fields)
{
  const std::string path = temp_path("file_sql_csv_basic.csv");
  const char *content =
      "id,name,score,active,day,ts\n"
      "1,alice,1.5,true,2024-01-15,2024-01-15 10:30:00\n"
      "2,\"bob \"\"the builder\"\"\",2,false,2024-02-29,2020-05-01 00:00:01\n"
      "3,\"line1\nline2\",NA,,,\n";
  ASSERT_TRUE(write_file(path, content, static_cast<int64_t>(strlen(content))));
  Options options;
  options.null_string_ = "NA";
  const ReadResult result = read_all(path, options);
  EXPECT_EQ(Status::OK, result.status_) << result.error_;
  // The third row leaves active/day/ts empty.  An empty field is a value, not
  // NULL (only a matching nullstr becomes NULL), so those columns widen to
  // VARCHAR while score stays DOUBLE because "NA" is the configured null marker.
  EXPECT_EQ("id:bigint,name:varchar,score:double,active:varchar,day:varchar,ts:varchar",
            describe(result.columns_));
  ASSERT_EQ(3, static_cast<int>(result.rows_.size()));
  EXPECT_EQ("2|bob \"the builder\"|2|false|2024-02-29|2020-05-01 00:00:01",
            result.rows_[1][0] + "|" + result.rows_[1][1] + "|" + result.rows_[1][2] + "|" +
                result.rows_[1][3] + "|" + result.rows_[1][4] + "|" + result.rows_[1][5]);
  // A newline inside a quoted field stays inside the value.
  EXPECT_EQ("line1\nline2", result.rows_[2][1]);
  EXPECT_EQ("3", result.rows_[2][0]);
  EXPECT_EQ("NULL", result.rows_[2][2]);
  unlink(path.c_str());
}

