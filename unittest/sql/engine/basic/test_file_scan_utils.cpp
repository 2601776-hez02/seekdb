TEST(FileSqlScanUtils, options_snapshot_round_trips)
{
  Options options;
  options.format_ = FileFormat::NDJSON;
  options.delimiter_ = ';';
  options.quote_ = '\'';
  options.escape_ = '\\';
  options.header_ = false;
  options.null_string_ = "NA";
  options.skip_rows_ = 2;
  std::vector<Column> columns;
  Column column;
  column.name_ = "alpha";
  column.type_ = ColumnType::DOUBLE;
  columns.push_back(column);
  column.name_ = "beta";
  column.type_ = ColumnType::DATETIME;
  columns.push_back(column);
  std::vector<std::string> files;
  files.push_back("/tmp/a.csv");
  const std::string encoded = encode_options(options, "/tmp/a.csv", columns, 1024, 2048, files);

  Options decoded;
  std::string path;
  std::vector<Column> decoded_columns;
  std::vector<std::string> decoded_files;
  int64_t size = 0;
  int64_t modify_time = 0;
  EXPECT_EQ(Status::OK, decode_options(encoded.data(), static_cast<int64_t>(encoded.size()),
                                       decoded, path, decoded_columns, size, modify_time,
                                       decoded_files));
  EXPECT_EQ("/tmp/a.csv", path);
  EXPECT_EQ(1024, size);
  EXPECT_EQ(2048, modify_time);
  EXPECT_EQ(FileFormat::NDJSON, decoded.format_);
  EXPECT_EQ(';', decoded.delimiter_);
  EXPECT_EQ('\'', decoded.quote_);
  EXPECT_EQ('\\', decoded.escape_);
  EXPECT_FALSE(decoded.header_);
  EXPECT_EQ("NA", decoded.null_string_);
  EXPECT_EQ(2, decoded.skip_rows_);
  ASSERT_EQ(2, static_cast<int>(decoded_columns.size()));
  EXPECT_EQ("alpha:double,beta:datetime", describe(decoded_columns));
  ASSERT_EQ(1, static_cast<int>(decoded_files.size()));
  EXPECT_EQ("/tmp/a.csv", decoded_files[0]);
}

TEST(FileSqlScanUtils, inference_rules_are_deterministic)
{
  EXPECT_EQ(ColumnType::BIGINT, detect_text_type("42", 2));
  EXPECT_EQ(ColumnType::DOUBLE, detect_text_type("1e5", 3));
  EXPECT_EQ(ColumnType::BOOLEAN, detect_text_type("TRUE", 4));
  EXPECT_EQ(ColumnType::DATE, detect_text_type("2024-02-29", 10));
  EXPECT_EQ(ColumnType::DATETIME, detect_text_type("2024-02-29 10:00:00", 19));
  EXPECT_EQ(ColumnType::VARCHAR, detect_text_type("2023-02-29", 10));
  EXPECT_EQ(ColumnType::VARCHAR, detect_text_type("algorithm", 9));
  // Widening: numbers widen to double, date plus datetime widens to datetime,
  // and anything mixed with text falls back to varchar.
  EXPECT_EQ(ColumnType::DOUBLE, merge_column_type(ColumnType::BIGINT, ColumnType::DOUBLE));
  EXPECT_EQ(ColumnType::DATETIME, merge_column_type(ColumnType::DATE, ColumnType::DATETIME));
  EXPECT_EQ(ColumnType::VARCHAR, merge_column_type(ColumnType::BOOLEAN, ColumnType::BIGINT));
  EXPECT_EQ(ColumnType::BIGINT, merge_column_type(ColumnType::SQL_NULL, ColumnType::BIGINT));
}

